def _apply_v4(base: str) -> str:
    text = base
    for old, new in _V4_EDITS:
        if text.count(old) != 1:
            raise AssertionError(f"v4 편집 대상이 v3 본문에 정확히 한 번 있지 않다: {old[:30]}")
        text = text.replace(old, new)
    return text


